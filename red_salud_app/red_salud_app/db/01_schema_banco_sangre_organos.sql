-- =====================================================================
-- 01_schema_banco_sangre_organos.sql
-- Crea el usuario de la aplicación, la base de datos y todas las tablas.
--
-- Ejecutar como superusuario de PostgreSQL (en CentOS: usuario postgres),
-- indicando la contraseña que usará Flask para conectarse:
--
--   sudo -u postgres psql -v app_password='CambiaEstaClave' < 01_schema_banco_sangre_organos.sql
--
-- OJO: si la base banco_sangre_organos ya existe, se BORRA y se vuelve a
-- crear (así el script se puede correr las veces que sea necesario).
-- =====================================================================
\set ON_ERROR_STOP on

\if :{?app_password}
\else
    \echo 'ERROR: falta la contraseña del usuario de la aplicación.'
    \echo 'Uso: sudo -u postgres psql -v app_password=''TuClave'' < 01_schema_banco_sangre_organos.sql'
    \quit
\endif

-- Base de datos y usuario de la aplicación ----------------------------
DROP DATABASE IF EXISTS banco_sangre_organos WITH (FORCE);

SELECT 'CREATE ROLE app_banco LOGIN'
WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app_banco')
\gexec
ALTER ROLE app_banco WITH LOGIN PASSWORD :'app_password';

CREATE DATABASE banco_sangre_organos
    WITH ENCODING 'UTF8' TEMPLATE template0;

ALTER DATABASE banco_sangre_organos SET timezone TO 'America/Monterrey';

\c banco_sangre_organos

-- pgcrypto: crypt() y gen_salt() para guardar y validar contraseñas con bcrypt
CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- Permisos del usuario de la aplicación: solo lectura/escritura de datos
-- (no puede borrar ni cambiar tablas). Aplica a todo lo que se cree después
-- con este mismo usuario administrador (tablas, vistas, secuencias).
GRANT CONNECT ON DATABASE banco_sangre_organos TO app_banco;
GRANT USAGE ON SCHEMA public TO app_banco;
ALTER DEFAULT PRIVILEGES IN SCHEMA public
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO app_banco;
ALTER DEFAULT PRIVILEGES IN SCHEMA public
    GRANT USAGE, SELECT ON SEQUENCES TO app_banco;

