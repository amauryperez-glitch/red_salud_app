-- =====================================================================
-- MATCHING, ASIGNACIONES Y RESERVAS  (reglas 7.4, 7.8 a 7.14, 7.16)
-- Distancia (7.16) se calcula con latitud/longitud de direcciones_institucion.
-- FEFO (7.14) se resuelve ordenando por fecha_hora_caducidad.
-- =====================================================================

CREATE TABLE matching (
    id_matching INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_solicitud_detalle INTEGER NOT NULL,
    id_recurso INTEGER NOT NULL,
    id_resultado_compatibilidad SMALLINT NOT NULL,
    disponible BOOLEAN NOT NULL,
    explicacion TEXT,
    fecha_hora_calculo TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_matching PRIMARY KEY (id_matching),
    CONSTRAINT uq_matching_detalle_recurso UNIQUE (id_solicitud_detalle, id_recurso),
    CONSTRAINT uq_matching_matching_recurso UNIQUE (id_matching, id_recurso),
    CONSTRAINT fk_matching_solicitudes_detalle FOREIGN KEY (id_solicitud_detalle)
        REFERENCES solicitudes_detalle (id_solicitud_detalle),
    CONSTRAINT fk_matching_recursos FOREIGN KEY (id_recurso)
        REFERENCES recursos (id_recurso),
    CONSTRAINT fk_matching_cat_resultados_compatibilidad FOREIGN KEY (id_resultado_compatibilidad)
        REFERENCES cat_resultados_compatibilidad (id_resultado_compatibilidad)
);

-- id_recurso se repite aquí (además de en matching) para poder garantizar la
-- regla 7.4 con un índice único parcial en reservas. La FK compuesta evita
-- que id_recurso difiera del recurso del matching.
CREATE TABLE asignaciones (
    id_asignacion INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_matching INTEGER NOT NULL,
    id_recurso INTEGER NOT NULL,
    id_personal INTEGER NOT NULL,
    id_estado_asignacion SMALLINT NOT NULL,
    fecha_hora_asignacion TIMESTAMPTZ NOT NULL DEFAULT now(),
    motivo VARCHAR(255),
    CONSTRAINT pk_asignaciones PRIMARY KEY (id_asignacion),
    CONSTRAINT uq_asignaciones_matching UNIQUE (id_matching),
    CONSTRAINT uq_asignaciones_asignacion_recurso UNIQUE (id_asignacion, id_recurso),
    CONSTRAINT fk_asignaciones_matching FOREIGN KEY (id_matching, id_recurso)
        REFERENCES matching (id_matching, id_recurso),
    CONSTRAINT fk_asignaciones_personal FOREIGN KEY (id_personal)
        REFERENCES personal (id_personal),
    CONSTRAINT fk_asignaciones_cat_estados_asignacion FOREIGN KEY (id_estado_asignacion)
        REFERENCES cat_estados_asignacion (id_estado_asignacion)
);

CREATE TABLE reservas (
    id_reserva INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_asignacion INTEGER NOT NULL,
    id_recurso INTEGER NOT NULL,
    id_personal INTEGER NOT NULL,
    id_estado_reserva SMALLINT NOT NULL,
    fecha_hora_inicio TIMESTAMPTZ NOT NULL,
    fecha_hora_fin TIMESTAMPTZ,
    CONSTRAINT pk_reservas PRIMARY KEY (id_reserva),
    CONSTRAINT fk_reservas_asignaciones FOREIGN KEY (id_asignacion, id_recurso)
        REFERENCES asignaciones (id_asignacion, id_recurso),
    CONSTRAINT fk_reservas_personal FOREIGN KEY (id_personal)
        REFERENCES personal (id_personal),
    CONSTRAINT fk_reservas_cat_estados_reserva FOREIGN KEY (id_estado_reserva)
        REFERENCES cat_estados_reserva (id_estado_reserva),
    CONSTRAINT chk_reservas_fechas CHECK (fecha_hora_fin IS NULL OR fecha_hora_fin >= fecha_hora_inicio)
);

-- Regla 7.4: un recurso no puede tener más de una reserva activa a la vez.
-- Se asume id_estado_reserva = 1 -> 'Activa' (según el catálogo de la hoja 3FN).
CREATE UNIQUE INDEX uq_reservas_recurso_activa
    ON reservas (id_recurso)
    WHERE id_estado_reserva = 1;

