    id_direccion INTEGER NOT NULL,
    telefono VARCHAR(15),
    correo VARCHAR(150),
    CONSTRAINT pk_instituciones PRIMARY KEY (id_institucion),
    CONSTRAINT uq_instituciones_nombre UNIQUE (nombre),
    CONSTRAINT uq_instituciones_direccion UNIQUE (id_direccion),
    CONSTRAINT fk_instituciones_cat_tipos_instituciones FOREIGN KEY (id_tipo_institucion)
        REFERENCES cat_tipos_instituciones (id_tipo_institucion),
    CONSTRAINT fk_instituciones_cat_estados_institucion FOREIGN KEY (id_estado_institucion)
        REFERENCES cat_estados_institucion (id_estado_institucion),
    CONSTRAINT fk_instituciones_direcciones_institucion FOREIGN KEY (id_direccion)
        REFERENCES direcciones_institucion (id_direccion),
    CONSTRAINT chk_instituciones_nombre CHECK (length(trim(nombre)) > 0),
    CONSTRAINT chk_instituciones_telefono CHECK (telefono ~ '^[0-9]{10,15}$'),
    CONSTRAINT chk_instituciones_correo CHECK (correo ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$')
);

